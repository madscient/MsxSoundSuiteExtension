#!/usr/bin/env python3
"""
Copy the published documents out of the source repositories into docs/.

Usage:
    python tools/sync_docs.py [--check]

docs/ is committed so that GitHub renders it without access to the private
sources. --check reports what would change and returns non-zero instead of
writing, for use before tagging a release.

Documents that were co-located in doc/ stay co-located under docs/<key>/,
and doc/en/ under docs/<key>/en/, so links between them keep working;
links that pointed into a private source tree are unlinked via
manifest.LINK_REWRITE.
"""
import argparse
import os
import posixpath
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import manifest

LINK_RE = re.compile(r"\[([^\]]*)\]\(([^)]+)\)")

# The two indexes, keyed by the "docs" list they are built from.
INDEXES = {
    "docs": {
        "file": "README.md",
        "head": ["# ドキュメント", "", "日本語 | [English](README.en.md)", "",
                 "MSX Sound Suite Extension に含まれる各拡張BASICの仕様書。"],
        "development": "開発",
    },
    "docs_en": {
        "file": "README.en.md",
        "head": ["# Documentation", "", "[日本語](README.md) | English", "",
                 "The specifications of the BASIC extensions in MSX Sound "
                 "Suite Extension. Each one is a translation of a Japanese "
                 "original, which it links to and which is authoritative "
                 "where the two differ."],
        "development": "Development",
    },
}
LANGS = list(INDEXES)


def copies(entry):
    for lang in LANGS:
        yield from entry.get(lang, [])


def rewrite_links(text, entry, src_rel, dst_rel):
    src_label = f"{entry['key']}/{src_rel}"
    copied = {src: dst for src, dst, _ in copies(entry)}
    unknown = set()

    def repl(m):
        label, target = m.group(1), m.group(2)
        if target.startswith(("http://", "https://", "#", "mailto:")):
            return m.group(0)
        if target in manifest.LINK_REWRITE:
            new = manifest.LINK_REWRITE[target]
            return label if new is None else f"[{label}]({new})"
        path, sep, anchor = target.partition("#")
        hit = copied.get(posixpath.normpath(
            posixpath.join(posixpath.dirname(src_rel), path)))
        if hit is not None:
            new = posixpath.relpath(hit, posixpath.dirname(dst_rel))
            return f"[{label}]({new}{sep}{anchor})"
        if target.startswith(("../", "/")) or "/" in target:
            unknown.add(target)
        return m.group(0)

    out = LINK_RE.sub(repl, text)
    for target in sorted(unknown):
        print(f"WARNING: {src_label}: link leaves the copy and has no "
              f"rewrite rule: {target}")
    return out


def render(entry, src_rel, dst_rel):
    src = manifest.abspath(entry["path"], src_rel)
    with open(src, "r", encoding="utf-8") as f:
        text = f.read()
    text = rewrite_links(text, entry, src_rel, dst_rel)
    banner = (f"<!-- generated by tools/sync_docs.py from "
              f"{entry['path']}/{src_rel} - do not edit here -->\n")
    return banner + text


def index(lang):
    spec = INDEXES[lang]
    n = LANGS.index(lang)
    lines = spec["head"] + [""]
    # 図は tools/diagram.py が描く。ここが唯一の埋め込み箇所ではないので、
    # 描き直しの検査は package.py が diagram.py --check で行う。
    for _, dst_rel, *labels in manifest.DIAGRAMS:
        lines += [f"![{labels[n]}]({dst_rel})", ""]
    for key, title in manifest.DOC_SECTIONS:
        entry = manifest.repo(key)
        lines += [f"## {title}", ""]
        for _, dst_rel, label in entry.get(lang, []):
            lines.append(f"- [{label}]({dst_rel})")
        lines.append("")
    lines += [f"## {spec['development']}", ""]
    for dst_rel, *labels in manifest.LOCAL_DOCS:
        lines.append(f"- [{labels[n]}]({dst_rel})")
    lines.append("")
    return "\n".join(lines)


def write(path, text, check):
    full = manifest.abspath(manifest.DOCS, path)
    old = None
    if os.path.isfile(full):
        with open(full, "r", encoding="utf-8", newline="") as f:
            old = f.read()
    if old == text:
        print(f"    {path} (unchanged)")
        return False
    if check:
        print(f"    {path} (OUT OF DATE)")
        return True
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"    {path} ({'updated' if old is not None else 'new'})")
    return True


def dangling_links():
    """Relative links in docs/ that do not resolve.

    rewrite_links only warns about targets that leave the copy. A bare
    co-located name resolves inside the source tree and looks fine there,
    so a document that is linked but absent from manifest.REPOS reaches
    docs/ as a dead link with nothing said.
    """
    root = manifest.abspath(manifest.DOCS)
    bad = []
    for dirpath, _, names in os.walk(root):
        for name in sorted(names):
            if not name.endswith(".md"):
                continue
            path = os.path.join(dirpath, name)
            with open(path, "r", encoding="utf-8") as f:
                text = f.read()
            for _, target in LINK_RE.findall(text):
                target = target.split("#", 1)[0]
                if not target or target.startswith(
                        ("http://", "https://", "mailto:")):
                    continue
                if not os.path.exists(os.path.join(dirpath, target)):
                    rel = os.path.relpath(path, root).replace(os.sep, "/")
                    bad.append((rel, target))
    return bad


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true",
                        help="report staleness without writing")
    args = parser.parse_args()

    stale = False
    for entry in manifest.REPOS:
        print(f"=== {entry['title']} ===")
        for src_rel, dst_rel, _ in copies(entry):
            src = manifest.abspath(entry["path"], src_rel)
            if not os.path.isfile(src):
                print(f"ERROR: missing {entry['path']}/{src_rel} "
                      f"(git submodule update --init)")
                return 1
            stale |= write(dst_rel, render(entry, src_rel, dst_rel), args.check)
    print("=== index ===")
    for lang in LANGS:
        stale |= write(INDEXES[lang]["file"], index(lang), args.check)

    if args.check and stale:
        print("\ndocs/ is out of date; run tools/sync_docs.py")
        return 1

    print("=== links ===")
    bad = dangling_links()
    for src, target in bad:
        print(f"ERROR: {src}: link to {target} has no copy in docs/")
    if bad:
        print("\nlist the target in the repository's \"docs\" entry in "
              "manifest.py if it is a document, run tools/diagram.py if it "
              "is a diagram, or drop the link at the source")
        return 1
    print("    all relative links resolve")

    print("\nOK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
